"""
Write the network mapping for the shortlist size sweep, so it can be checked against the networks folder.

Produces experiment_networks.md: one row per planned evaluation, naming the first and the second network,
the fold, the test set and the output file, plus the config fields each pairing was derived from.

Nothing here runs a network, it only reads config.json and lists what is on disk.

Usage:
    python list_experiment_networks.py
    python list_experiment_networks.py --model_dir <networks folder> --output experiment_networks.md
"""

import argparse
import json
import os

from evaluate_shortlist_sizes import METHODS, str2intlist


DEFAULT_MODEL_DIR = ('/Users/bella/Academy/Research/ultrasound inexperienced operator/'
                     'Ultrasound slice selection/Networks/experiments_networks')


def read_config(model_dir, network_id):
    """
    Config of a network, or an empty dict when it is not on disk
    """
    path = os.path.join(model_dir, str(network_id), 'config.json')
    if not os.path.exists(path):
        return {}
    with open(path, 'r') as f:
        return json.load(f)


def describe(model_dir, network_id):
    """
    The config fields that identify a network, plus whether its weights are present
    """
    config = read_config(model_dir, network_id)
    model_path = os.path.join(model_dir, str(network_id), 'model.pt')
    data_dir = config.get('data_dir', '')
    return {
        'id': network_id,
        'model_name': config.get('model_name', 'missing'),
        'pos_only': config.get('pos_only', 'missing'),
        'num_classes': config.get('num_classes', 'missing'),
        'fold_from_data_dir': os.path.basename(data_dir.rstrip('/')) if data_dir else 'missing',
        'data_dir': data_dir,
        'weights_present': os.path.exists(model_path),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="List the networks used per experiment")
    parser.add_argument("--model_dir", type=str, default=DEFAULT_MODEL_DIR, help="folder holding the networks")
    parser.add_argument("--method", type=str, default='two-step (ours)', choices=sorted(METHODS.keys()),
                        help="which network pair the sweep uses")
    parser.add_argument("--shortlist_sizes", type=str2intlist, default='3,5,10',
                        help="comma separated candidate shortlist sizes")
    parser.add_argument("--output", type=str, default='experiment_networks.md', help="file to write")

    args = parser.parse_args()
    model_dirnames, model2_dirnames = METHODS[args.method]

    lines = []
    lines.append('# Networks used per experiment')
    lines.append('')
    lines.append('Generated by `list_experiment_networks.py` from the `config.json` of each network in')
    lines.append('`%s`.' % args.model_dir)
    lines.append('Re-run it to regenerate this file.')
    lines.append('')
    lines.append('Method under evaluation: **%s**, shortlist sizes **%s**.' %
                 (args.method, ', '.join(str(k) for k in args.shortlist_sizes)))
    lines.append('')

    lines.append('## How the pairing was derived')
    lines.append('')
    lines.append('The two-step approach applies the one-step network first and the second stage of the')
    lines.append('two-step approach to its shortlist. The two roles are told apart by `pos_only` in the')
    lines.append('config: the one-step network is trained on all frames (`pos_only: false`), the second')
    lines.append('stage only on relevant frames (`pos_only: true`). Folds are matched through `data_dir`.')
    lines.append('')
    lines.append('| role | network | model_name | pos_only | num_classes | fold from data_dir | model.pt |')
    lines.append('|---|---|---|---|---|---|---|')
    for fold in range(len(model2_dirnames)):
        for role, ids in (('first (one-step)', model_dirnames), ('second (two-step stage 2)', model2_dirnames)):
            d = describe(args.model_dir, ids[fold])
            lines.append('| %s | %s | %s | %s | %s | %s | %s |' % (
                role, d['id'], d['model_name'], d['pos_only'], d['num_classes'], d['fold_from_data_dir'],
                'present' if d['weights_present'] else 'MISSING'))
    lines.append('')

    lines.append('## Planned evaluations')
    lines.append('')
    lines.append('Each row is one run of `evaluate_frame_selection.py`. `_subopt` is the suboptimal-only test')
    lines.append('set (`--rel_only true`, scan list from `subopt_cases.txt`); the other row is the')
    lines.append('optimal-included test set, whose scans come from the fold test folder.')
    lines.append('')
    lines.append('| shortlist K | fold | first network | second network | test set | output file |')
    lines.append('|---|---|---|---|---|---|')
    for shortlist_size in args.shortlist_sizes:
        for fold in range(len(model2_dirnames)):
            first = model_dirnames[fold]
            second = model2_dirnames[fold]
            lines.append('| %d | %d | %s | %s | optimal-included | `%s/results/predictions_%s_k%d.xlsx` |' % (
                shortlist_size, fold, first, second, second, second, shortlist_size))
            lines.append('| %d | %d | %s | %s | suboptimal-only | `%s/results/predictions_%s_subopt_k%d.xlsx` |' % (
                shortlist_size, fold, first, second, second, second, shortlist_size))
    lines.append('')

    lines.append('## The other method pairs')
    lines.append('')
    lines.append('Not run by default, listed so the pairing above can be compared with them.')
    lines.append('')
    lines.append('| method | first networks | second networks |')
    lines.append('|---|---|---|')
    for name in sorted(METHODS):
        first_ids, second_ids = METHODS[name]
        marker = ' *(selected)*' if name == args.method else ''
        lines.append('| %s%s | %s | %s |' % (name, marker,
                                             ', '.join(str(i) for i in first_ids),
                                             ', '.join(str(i) for i in second_ids)))
    lines.append('')

    text = '\n'.join(lines) + '\n'
    out_path = args.output
    if not os.path.isabs(out_path):
        out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), out_path)
    with open(out_path, 'w') as f:
        f.write(text)
    print(text)
    print('Saved to %s' % out_path)
